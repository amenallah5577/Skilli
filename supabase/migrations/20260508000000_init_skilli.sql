create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  username text not null,
  bio text,
  avatar_url text,
  location text,
  points integer not null default 20 check (points >= 0),
  xp integer not null default 0 check (xp >= 0),
  rating numeric(3, 2) not null default 0 check (rating >= 0 and rating <= 5),
  created_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[a-z0-9_]{3,30}$')
);

create unique index if not exists profiles_username_lower_key
  on public.profiles (lower(username));

create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name text not null,
  category text,
  created_at timestamptz not null default now()
);

create unique index if not exists skills_name_lower_key
  on public.skills (lower(name));

create table if not exists public.user_teach_skills (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  skill_id bigint not null references public.skills(id) on delete cascade,
  level text not null check (level in ('beginner', 'intermediate', 'advanced')),
  created_at timestamptz not null default now(),
  unique (user_id, skill_id)
);

create table if not exists public.user_learn_skills (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  skill_id bigint not null references public.skills(id) on delete cascade,
  level text not null check (level in ('beginner', 'intermediate', 'advanced')),
  created_at timestamptz not null default now(),
  unique (user_id, skill_id)
);

create table if not exists public.sessions (
  id bigint generated by default as identity primary key,
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  learner_id uuid not null references public.profiles(id) on delete cascade,
  skill_id bigint not null references public.skills(id),
  status text not null default 'pending' check (
    status in ('pending', 'accepted', 'rejected', 'completed', 'cancelled')
  ),
  mode text not null default 'chat' check (mode in ('chat', 'voice', 'video')),
  goal text not null default 'Practice this skill with a clear learning goal',
  scheduled_at timestamptz,
  duration_minutes integer not null default 30 check (duration_minutes between 15 and 180),
  meeting_link text,
  note text,
  lesson_plan text[] not null default '{}',
  lesson_notes text not null default '',
  task_title text not null default 'Practice task',
  task_description text not null default '',
  task_status text not null default 'not_started' check (
    task_status in ('not_started', 'practicing', 'understood', 'mastered')
  ),
  task_submission text,
  task_feedback text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint sessions_different_users check (teacher_id <> learner_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.sessions(id) on delete cascade,
  reviewer_id uuid not null references public.profiles(id) on delete cascade,
  reviewed_user_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text check (comment is null or char_length(comment) <= 1000),
  created_at timestamptz not null default now(),
  unique (session_id, reviewer_id, reviewed_user_id),
  constraint reviews_no_self_review check (reviewer_id <> reviewed_user_id)
);

create table if not exists public.badges (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  icon text,
  created_at timestamptz not null default now()
);

create table if not exists public.user_badges (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  badge_id bigint not null references public.badges(id) on delete cascade,
  earned_at timestamptz not null default now(),
  unique (user_id, badge_id)
);

