create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, username, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1), 'New member'),
    'user_' || replace(substr(new.id::text, 1, 8), '-', ''),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

create or replace function private.validate_session_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
begin
  if tg_op = 'INSERT' then
    if new.status <> 'pending' then
      raise exception 'New sessions must start as pending';
    end if;

    if actor is not null and new.learner_id <> actor then
      raise exception 'Learner must be the authenticated user';
    end if;

    return new;
  end if;

  if old.teacher_id <> new.teacher_id
    or old.learner_id <> new.learner_id
    or old.skill_id <> new.skill_id then
    raise exception 'Session participants and skill cannot be changed';
  end if;

  if actor is null then
    return new;
  end if;

  if old.status = new.status then
    return new;
  end if;

  if old.status = 'pending'
    and new.status in ('accepted', 'rejected')
    and actor = old.teacher_id then
    return new;
  end if;

  if old.status in ('pending', 'accepted')
    and new.status = 'cancelled'
    and actor in (old.teacher_id, old.learner_id) then
    return new;
  end if;

  if old.status = 'accepted'
    and new.status = 'completed'
    and actor in (old.teacher_id, old.learner_id) then
    new.completed_at := coalesce(new.completed_at, now());
    return new;
  end if;

  raise exception 'Invalid session status transition';
end;
$$;

drop trigger if exists validate_session_update on public.sessions;
create trigger validate_session_update
before insert or update on public.sessions
for each row execute function private.validate_session_update();

create or replace function private.apply_session_completion_rewards()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles
  set points = points + 10,
      xp = xp + 20
  where id = new.teacher_id;

  update public.profiles
  set points = greatest(points - 10, 0),
      xp = xp + 5
  where id = new.learner_id;

  return new;
end;
$$;

drop trigger if exists apply_session_completion_rewards on public.sessions;
create trigger apply_session_completion_rewards
after update of status on public.sessions
for each row
when (old.status <> 'completed' and new.status = 'completed')
execute function private.apply_session_completion_rewards();

create or replace function private.refresh_profile_rating()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_user uuid;
begin
  target_user := coalesce(new.reviewed_user_id, old.reviewed_user_id);

  update public.profiles
  set rating = coalesce(
    (
      select round(avg(rating)::numeric, 2)
      from public.reviews
      where reviewed_user_id = target_user
    ),
    0
  )
  where id = target_user;

  return coalesce(new, old);
end;
$$;

drop trigger if exists refresh_profile_rating_insert on public.reviews;
create trigger refresh_profile_rating_insert
after insert or update or delete on public.reviews
for each row execute function private.refresh_profile_rating();

create or replace function private.apply_five_star_bonus()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.rating = 5 then
    update public.profiles
    set points = points + 3,
        xp = xp + 10
    where id = new.reviewed_user_id;
  end if;

  return new;
end;
$$;

drop trigger if exists apply_five_star_bonus on public.reviews;
create trigger apply_five_star_bonus
after insert on public.reviews
for each row execute function private.apply_five_star_bonus();

